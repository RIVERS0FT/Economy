from pathlib import Path


def replace_once(path, old, new):
    file = Path(path)
    text = file.read_text()
    if old not in text:
        raise RuntimeError(f'Missing authority text in {path}: {old[:120]!r}')
    file.write_text(text.replace(old, new, 1))


